const dictionaries: Record<Locale, Dict> = { en, fr, so, ar };

interface I18nContextValue {
  lang: Locale;
  dir: "ltr" | "rtl";
  setLang: (l: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Locale>("en");

  useEffect(() => {
    const saved = localStorage.getItem("placerambo:locale") as Locale | null;
    if (saved && ["en", "fr", "so", "ar"].includes(saved)) setLangState(saved);
  }, []);

  const setLang = (l: Locale) => {
    setLangState(l);
    localStorage.setItem("placerambo:locale", l);
    if (typeof document !== "undefined") {
      document.documentElement.dir = l === "ar" ? "rtl" : "ltr";
      document.documentElement.lang = l;
    }
  };

  const value = useMemo<I18nContextValue>(() => {
    const dict = dictionaries[lang];
    return {
      lang,
      dir: lang === "ar" ? "rtl" : "ltr",
      setLang,
      t: (key, vars) => {
        let str = dict[key] ?? dictionaries.en[key] ?? key;
        if (vars) {
          Object.entries(vars).forEach(([k, v]) => {
            str = str.replace(`{${k}}`, String(v));
          });
        }
        return str;
      },
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
